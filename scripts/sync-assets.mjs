/**
 * Publishes the media that pages and the room load: copies it from `src/` into `public/_assets/`
 * under a content-hashed name, writes responsive WebP widths for photos, and records everything
 * in `src/generated/media.ts` (`media['covers/<isbn>.jpg']`). Runs before `dev`, `build` and
 * `typecheck`; unchanged files are skipped.
 */
import { createHash } from 'node:crypto';
import { existsSync, mkdirSync, readdirSync, readFileSync, statSync, writeFileSync } from 'node:fs';
import { dirname, extname, join, relative } from 'node:path';
import sharp from 'sharp';

const ROOT = join(dirname(new URL(import.meta.url).pathname), '..');
const OUT = join(ROOT, 'public/_assets');
const MANIFEST = join(ROOT, 'src/generated/media.ts');
/** Widths offered in a srcset; a photo never grows past its own width. */
const WIDTHS = [480, 800, 1200, 1600, 2400];

const SOURCES = [
	{ dir: 'src/assets', prefix: '' },
	{ dir: 'src/content', prefix: 'content/' },
];
const IMAGE = new Set(['.png', '.jpg', '.jpeg', '.webp']);
const PLAIN = new Set(['.glb']);

const walk = (dir) =>
	readdirSync(dir, { withFileTypes: true }).flatMap((d) => {
		const p = join(dir, d.name);
		if (d.isDirectory()) return d.name === 'originals' ? [] : walk(p);
		return [p];
	});

const hashOf = (buf) => createHash('sha256').update(buf).digest('hex').slice(0, 10);

const write = (path, data) => {
	mkdirSync(dirname(path), { recursive: true });
	writeFileSync(path, data);
};

const entries = {};
for (const { dir, prefix } of SOURCES) {
	for (const file of walk(join(ROOT, dir))) {
		const ext = extname(file).toLowerCase();
		if (!IMAGE.has(ext) && !PLAIN.has(ext)) continue;
		const key = prefix + relative(join(ROOT, dir), file);
		const buf = readFileSync(file);
		const hash = hashOf(buf);
		const base = key.slice(0, -ext.length);
		const publicPath = `${base}.${hash}${ext}`;
		const target = join(OUT, publicPath);
		if (!existsSync(target)) write(target, buf);
		if (PLAIN.has(ext)) {
			entries[key] = { src: `/_assets/${publicPath}` };
			continue;
		}
		const { width, height } = await sharp(buf).metadata();
		const srcSet = [];
		for (const w of WIDTHS.filter((w) => w < width).concat(width)) {
			const out = `${base}.${hash}.w${w}.webp`;
			const path = join(OUT, out);
			if (!existsSync(path)) {
				write(path, await sharp(buf).resize({ width: w }).webp({ quality: 82 }).toBuffer());
			}
			srcSet.push({ src: `/_assets/${out}`, width: w });
		}
		entries[key] = {
			src: `/_assets/${publicPath}`,
			width,
			height,
			srcSet,
			file: relative(ROOT, file),
		};
	}
}

const body = `// GENERATED by scripts/sync-assets.mjs. Do not edit.
export const media = ${JSON.stringify(entries, null, '\t')} as const satisfies Record<string, MediaEntry>;

export type MediaEntry = {
	src: string;
	width?: number;
	height?: number;
	srcSet?: readonly { src: string; width: number }[];
	file?: string;
};

export type MediaKey = keyof typeof media;
`;
const current = existsSync(MANIFEST) ? readFileSync(MANIFEST, 'utf8') : '';
if (current !== body) write(MANIFEST, body);
const size = statSync(MANIFEST).size;
console.log(`sync-assets: ${Object.keys(entries).length} files, manifest ${size} bytes`);
